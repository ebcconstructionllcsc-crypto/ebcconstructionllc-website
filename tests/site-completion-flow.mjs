import assert from 'node:assert/strict';
import fs from 'node:fs';
import { JSDOM } from 'jsdom';

const pages = ['index.html','services.html','projects.html','about.html','contact.html','reviews.html'];
for (const page of pages) {
  const html = fs.readFileSync(page, 'utf8');
  assert.ok(!/Real (?:project photos|EBC work|EBC project work|work\.|photos)|(?:trabajos?|fotos|proyectos) reales|trabajo real|Photos and videos shown here come from|Las fotos y videos mostrados aquí provienen/i.test(html), `${page}: redundant project-authenticity copy`);
  assert.ok(!html.includes('drive.google.com'), `${page}: unreliable Drive media`);
  const dom = new JSDOM(html, { url: 'https://ebcconstructionllc.com/' + page, runScripts: 'outside-only' });
  const { window } = dom;
  const doc = window.document;
  assert.equal(doc.querySelectorAll('script[src^="assets/site-intro.js"]').length, 1);
  assert.ok(doc.querySelector('nav a[href="reviews.html"]'));
  assert.ok(doc.querySelector('link[href^="assets/site-completion.css"]'));
  for (const img of doc.querySelectorAll('img[src^="assets/"]')) assert.ok(fs.existsSync(img.getAttribute('src')), img.src);
  window.matchMedia = () => ({ matches: true });
  window.eval(fs.readFileSync('assets/site-intro.js', 'utf8'));
  assert.ok(!doc.querySelector('.site-intro'), 'reduced motion must skip the entrance');
  window.matchMedia = () => ({ matches: false });
  window.eval(fs.readFileSync('assets/site-intro.js', 'utf8'));
  const intro = doc.querySelector('.site-intro');
  assert.ok(intro, 'original page-specific entrance restored');
  intro.querySelector('img').dispatchEvent(new window.Event('load'));
  intro.querySelector('button').click();
  assert.equal(doc.querySelector('.site-intro'), null, 'entrance remains skippable');
  assert.ok(doc.querySelector('.menu-btn[aria-controls="primary-navigation"]'));
  assert.ok(doc.querySelector('#primary-navigation'));
  dom.window.close();
}
const dom = new JSDOM(fs.readFileSync('index.html','utf8'), { url:'https://ebcconstructionllc.com/', runScripts:'outside-only' });
const { window } = dom;
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLMediaElement.prototype.pause = () => {};
window.HTMLMediaElement.prototype.load = () => {};
window.eval(fs.readFileSync('assets/masterpiece.js','utf8'));
const first = window.document.querySelector('[data-lightbox]');
first.click();
const photo = window.document.querySelector('[data-dialog-image]');
const firstSrc = photo.src;
window.document.querySelectorAll('.lightbox-navigation button')[1].click();
assert.notEqual(photo.src, firstSrc, 'next photo should change the enlarged image');
window.document.querySelector('[data-video-src]').click();
assert.equal(window.document.querySelector('[data-dialog-video]').tagName, 'VIDEO');
assert.ok(window.document.querySelector('[data-dialog-video]').controls);
dom.window.close();
console.log('Site completion: six consistent pages, local photos, immediate access, image navigation and native video.');

// Check the public navigation as a keyboard user with unavailable browser storage.
const navigationDom = new JSDOM(fs.readFileSync('index.html', 'utf8'), { url: 'https://local.test/', runScripts: 'outside-only' });
const navigationWindow = navigationDom.window;
navigationWindow.matchMedia = () => ({ matches: true });
Object.defineProperty(navigationWindow, 'localStorage', { get() { throw new Error('Storage unavailable'); } });
navigationWindow.eval(fs.readFileSync('assets/app.js', 'utf8'));
const navigationDoc = navigationWindow.document;
const menu = navigationDoc.querySelector('.menu-btn');
menu.click();
assert.equal(navigationDoc.querySelector('main').inert, true);
assert.equal(navigationDoc.activeElement, navigationDoc.querySelector('nav a'));
navigationWindow.dispatchEvent(new navigationWindow.KeyboardEvent('keydown', { key: 'Tab', shiftKey: true }));
assert.equal(navigationDoc.activeElement, menu, 'Shift+Tab wraps inside mobile menu');
navigationWindow.dispatchEvent(new navigationWindow.KeyboardEvent('keydown', { key: 'Escape' }));
assert.equal(navigationDoc.querySelector('main').inert, false);
assert.equal(navigationDoc.activeElement, menu, 'Escape restores menu focus');
navigationDoc.querySelector('[data-lang-btn="es"]').click();
assert.equal(navigationDoc.documentElement.lang, 'es', 'language must work when storage is blocked');
assert.match(navigationDoc.querySelector('.hero-media img').alt, /Equipo de EBC/);
assert.equal(navigationDoc.querySelector('.hero video'), null, 'large original poster without an automatic video download');
assert.ok(navigationDoc.querySelector('.intro-grid a[href="about.html"]'), 'restore About access in homepage content');
const presentation = fs.readFileSync('assets/public-quality.css', 'utf8');
assert.ok(!presentation.includes('#182b25'), 'no green interface palette');
assert.equal(navigationDoc.querySelector('.quality-hero-photo'), null, 'remove split hero');
const schema = JSON.parse(navigationDoc.querySelector('script[type="application/ld+json"]').textContent);
assert.equal(schema.openingHoursSpecification[0].opens, '07:00');
assert.equal(schema.address.streetAddress, undefined, 'service-area business must not invent an office');
assert.ok(!schema.sameAs.some(url => url.includes('linkedin.com/in/')), 'personal LinkedIn is not the company identity');
assert.ok(fs.readFileSync('sitemap.xml', 'utf8').includes('/reviews.html'));
navigationWindow.close();
console.log('Public quality: keyboard navigation, blocked storage, bilingual alt text, confirmed local business data and review indexing.');
